"""Git 钩子：把「提交前先审一遍」变成自动动作。

参考 CodeRabbit 的 pre-merge checks（把检查放到合入前）和 aider 的 lint/test 钩子，
这里提供最轻的一档：**pre-commit 提交前跑离线审查**，不需要 API Key、不联网。

生成的钩子带固定标记，所以：
    · 重复安装只会更新，不会叠加
    · 卸载只删自己写的，不碰别人的钩子
    · 遇到已有的第三方钩子，默认拒绝覆盖；--force 会先备份再装
"""
from __future__ import annotations

import os
import shutil
import subprocess
import time
from pathlib import Path

MARKER_START = '# >>> reviewagent pre-commit >>>'
MARKER_END = '# <<< reviewagent pre-commit <<<'
HOOK_NAME = 'pre-commit'
SEVERITIES = ('low', 'medium', 'high', 'critical')


class HookError(RuntimeError):
    """钩子安装/卸载失败（例如目标已存在且不是本工具生成的）。"""


def hooks_dir(repo: str) -> Path:
    """用 git 自己回答 hooks 目录在哪（兼容 worktree / 自定义 core.hooksPath）。"""
    root = Path(repo).resolve()
    proc = subprocess.run(
        ['git', '-C', str(root), 'rev-parse', '--git-path', 'hooks'],
        capture_output=True, text=True,
    )
    if proc.returncode != 0:
        raise HookError(f'不是 Git 仓库：{root}')
    path = Path(proc.stdout.strip())
    if not path.is_absolute():
        path = root / path
    return path


def hook_path(repo: str) -> Path:
    return hooks_dir(repo) / HOOK_NAME


def build_hook(python: str, cli: str, severity: str = 'high') -> str:
    """生成 hook 脚本。注释全用 ASCII —— 和 .bat 同样的教训，避免解析意外。"""
    if severity not in SEVERITIES:
        raise HookError(f'severity 必须是 {"/".join(SEVERITIES)} 之一')
    return f'''#!/bin/sh
{MARKER_START}
# Generated by: python ascend_cli.py install-hook
# Runs an offline review on staged changes (no API key needed).
# Exits non-zero when issues at or above "{severity}" are found,
# so the commit is blocked. Remove with: install-hook --remove
ROOT="$(git rev-parse --show-toplevel)" || exit 1
cd "$ROOT" || exit 1
"{python}" "{cli}" review --staged --offline --require-full --fail-on {severity}
{MARKER_END}
'''


def is_installed(repo: str) -> bool:
    path = hook_path(repo)
    try:
        return MARKER_START in path.read_text(encoding='utf-8', errors='replace')
    except OSError:
        return False


def install(repo: str, python: str, cli: str, severity: str = 'high',
            force: bool = False) -> tuple[Path, str]:
    """安装或更新钩子，返回 (路径, 动作)。动作：created / updated / backup+created。"""
    path = hook_path(repo)
    path.parent.mkdir(parents=True, exist_ok=True)
    action = 'created'
    content = build_hook(python, cli, severity)

    if path.exists():
        existing = path.read_text(encoding='utf-8', errors='replace')
        if MARKER_START in existing:
            action = 'updated'
        elif not force:
            raise HookError(
                f'{path} 已存在且不是本工具生成的钩子。\n'
                '  先看一遍它的内容；确认要替换就加 --force（会先备份）。'
            )
        else:
            backup = path.with_suffix(f'.bak.{time.strftime("%Y%m%d-%H%M%S")}')
            shutil.copy2(path, backup)
            action = f'备份到 {backup.name} 后安装'

    path.write_text(content, encoding='utf-8', newline='\n')
    try:
        os.chmod(path, 0o755)
    except OSError:
        pass
    return path, action


def remove(repo: str) -> tuple[Path, str]:
    """只删除本工具生成的钩子；别人的钩子一律不动。"""
    path = hook_path(repo)
    if not path.exists():
        return path, '不存在'
    text = path.read_text(encoding='utf-8', errors='replace')
    if MARKER_START not in text:
        raise HookError(f'{path} 不是本工具生成的钩子，拒绝删除')
    path.unlink()
    return path, '已删除'
